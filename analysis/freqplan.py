#!/usr/bin/env python3
"""
Frequency plan + mixer spur / image analysis for the RFFC507x -> 2.44 GHz IF -> ESP32-S31 chain.

For each tuned RF and LO choice it enumerates every m*f_in +/- n*LO product (m,n <= 5) that lands
inside the ESP32 capture window (IF +/- BW/2) for an input f_in that is INSIDE the preselector passband
(spurs from inputs outside the passband get the preselector's rejection on top and are ignored here).

Spur rejection model R(m,n) [dBc, desired (1,1) = 0, equal input power, -10 dBm at mixer input] is a
GENERIC double-balanced active (Gilbert) mixer table - ASSUMPTION, see doc s.4.  Image (1,1 other
sideband) has R = 0: only the preselector rejects it.

Outputs: export/auto_freqplan.png, export/auto_spurs.png, export/freqplan_tables.md
"""
import os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__)); EXP = os.path.join(HERE, "export")
os.makedirs(EXP, exist_ok=True)

IF0 = 2440.0          # MHz: = 61 x 40 MHz ref harmonic, parked on the DC spike (see RISK_RESEARCH R2)
BW = 40.0             # capture window (40 MS/s complex)
LO_MIN, LO_MAX = 85.0, 4200.0      # RFFC507x [DS]
MIX_MIN, MIX_MAX = 30.0, 6000.0    # RFFC507x mixer input range [DS]

# generic spur table, rows m (RF harmonic) 0..5, cols n (LO harmonic) 0..5
R = np.array([
    [99, 99, 99, 99, 99, 99],   # m=0 (LO leakage handled separately as absolute level)
    [40,  0, 35, 15, 40, 22],   # m=1 : RF feedthrough ~40 dBc [DS fig], 1x3 ~ 10-15 dB (square-wave LO 3rd harmonic)
    [55, 55, 60, 60, 65, 65],
    [65, 65, 70, 68, 72, 72],
    [75, 75, 75, 75, 75, 75],
    [80, 80, 80, 80, 80, 80]], dtype=float)

PRESEL = {
    "LB":   [(30, 1750)],
    "MB":   [(1750, 2150)],      # D14 mid band, BPF after LNA_LB
    "HB":   [(3100, 6000)],      # D13: HB edge raised to 3.1 GHz
    "HB1":  [(3100, 3700)],      # proposed split
    "HB2":  [(3700, 6000)],
}

def spur_inputs(lo, m, n):
    """Intervals of f_in (MHz) for which |m f +/- n lo| falls in [IF0-BW/2, IF0+BW/2]."""
    a, b = IF0 - BW / 2, IF0 + BW / 2
    iv = []
    if m == 0:
        return iv
    for s_if in (+1, -1):          # m f - n lo = +/-IF   and   m f + n lo = IF
        lo_ = (s_if * a + n * lo) / m; hi_ = (s_if * b + n * lo) / m
        iv.append(tuple(sorted((lo_, hi_))))
    iv.append(tuple(sorted(((a - n * lo) / m, (b - n * lo) / m))))
    return [(max(x, 0.0), y) for x, y in iv if y > 0]

def analyse(rf, lo, band):
    """Return list of (rej_dB, m, n, f_lo, f_hi, kind) for spurs whose input range overlaps passband."""
    out = []
    pb = PRESEL[band]
    for m in range(1, 6):
        for n in range(0, 6):
            for (x, y) in spur_inputs(lo, m, n):
                for (p0, p1) in pb:
                    lo_i, hi_i = max(x, p0, MIX_MIN), min(y, p1, MIX_MAX)
                    if lo_i < hi_i:
                        if m == 1 and n == 1 and lo_i - 1 <= rf <= hi_i + 1:
                            continue                     # desired response
                        kind = "IMAGE" if (m == 1 and n == 1) else (("IF feedthrough" if m == 1 else f"RF harmonic {m}x0") if n == 0 else f"{m}x{n}")
                        rej = 0.0 if kind == "IMAGE" else R[m, n]
                        out.append((rej, m, n, lo_i, hi_i, kind))
    return sorted(out)

def plans(rf):
    """Candidate (label, LO, band) for an RF frequency."""
    c = []
    if MIX_MIN <= rf <= 1750:
        for lab, lo in (("LB hi-side LO=IF+RF", IF0 + rf), ("LB lo-side LO=IF-RF", IF0 - rf)):
            if LO_MIN <= lo <= LO_MAX:
                c.append((lab, lo, "LB"))
    if 1750 < rf <= 2150:
        c.append(("MB lo-side LO=IF-RF", IF0 - rf, "MB"))
    if 3100 <= rf <= 6000:
        lo = rf - IF0
        if LO_MIN <= lo <= LO_MAX:
            c.append(("HB single filter", lo, "HB"))
            c.append(("HB split filters", lo, "HB1" if rf < 3700 else "HB2"))
    return c

def worst(rf, lo, band):
    sp = analyse(rf, lo, band)
    return (sp[0][0], sp[0]) if sp else (99.0, None)

def main():
    global IF0
    # ---------------------------------------------------------------- tables at representative RFs
    md = ["# Frequency plan & spur tables (auto-generated by analysis/freqplan.py)\n",
          f"IF = {IF0} MHz, capture window +/-{BW/2:.0f} MHz, spur table = generic Gilbert-cell (assumption). "
          "Only spurs whose input lies INSIDE the preselector passband are listed (worst 6).\n"]
    for rf in [100, 137, 433, 915, 1090, 1575, 1700, 3000, 3500, 4000, 4880, 5200, 5800]:
        for lab, lo, band in plans(rf):
            sp = analyse(rf, lo, band)[:6]
            md.append(f"**RF {rf} MHz - {lab}** (LO {lo:.0f} MHz, presel {PRESEL[band]})\n")
            if not sp:
                md.append("- no spurs with R < 99 dB in passband\n"); continue
            for rej, m, n, a, b, kind in sp:
                md.append(f"- {kind:16s} m={m} n={n}: input {a:7.1f}-{b:7.1f} MHz, rejection ~{rej:.0f} dBc")
            md.append("")
    with open(os.path.join(EXP, "freqplan_tables.md"), "w") as f:
        f.write("\n".join(md) + "\n")

    BLUE, ORANGE, AQUA, YELLOW, MAG = "#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"

    # ---------------------------------------------------------------- plot 1: frequency plan
    fig, ax = plt.subplots(figsize=(9.5, 5.2), dpi=130)
    rf_lb = np.linspace(30, 1750, 300); rf_hb = np.linspace(3100, 6000, 300); rf_mb = np.linspace(1750, 2150, 100)
    ax.plot(rf_lb, IF0 + rf_lb, color=BLUE, lw=2, label="LO, low band (hi-side: LO = IF + RF)")
    ax.plot(rf_hb, rf_hb - IF0, color=ORANGE, lw=2, label="LO, high band (LO = RF - IF)")
    ax.plot(rf_mb, IF0 - rf_mb, color=YELLOW, lw=2, label="LO, mid band (LO = IF - RF)")
    ax.plot(rf_mb, 2 * IF0 - rf_mb, color=YELLOW, lw=1.5, ls="--", label="Image, mid band (2 IF - RF)")
    ax.plot(rf_lb, 2 * IF0 + rf_lb, color=BLUE, lw=1.5, ls="--", label="Image, low band (2 IF + RF)")
    ax.plot(rf_hb, np.abs(rf_hb - 2 * IF0), color=ORANGE, lw=1.5, ls="--", label="Image, high band |RF - 2 IF|")
    ax.plot(rf_lb, rf_lb + IF0 / 2, color=BLUE, lw=1.2, ls=":", label="Half-IF (2x2) input, low band")
    ax.plot(rf_hb, 3 * (rf_hb - IF0) + IF0, color=ORANGE, lw=1.2, ls=":", label="1x3 input 3 LO + IF, high band")
    ax.plot(rf_hb, 3 * (rf_hb - IF0) - IF0, color=ORANGE, lw=1.2, ls=(0, (1, 3)), label="1x3 input 3 LO - IF, high band")
    ax.axhspan(LO_MAX, 7000, color="#f3d6d6", alpha=0.6, lw=0)
    ax.text(150, LO_MAX + 80, "above LO max (4.2 GHz)", fontsize=7.5, color="#8a3b3b")
    ax.axvspan(2150, 2800, color="#d9ead3", alpha=0.7, lw=0)
    ax.text(2185, 6650, "native ESP32\n2.15-2.80 GHz", fontsize=7.5, color="#2f6b2f")
    ax.axhspan(IF0 - 42, IF0 + 42, color="#e6e6e6", lw=0)
    ax.text(3950, IF0 + 60, "IF filter 2400-2483", fontsize=7.5, color="#555")
    ax.axvspan(2800, 3100, color="#f2f2f2", lw=0)
    ax.text(2830, 400, "gap", fontsize=7.5, color="#777")
    ax.axvline(2 * IF0, color="#999", lw=0.8); ax.text(2 * IF0 + 30, 150, "RF = 2 IF: LO lands in IF", fontsize=7.5, color="#555")
    ax.set_xlim(0, 6100); ax.set_ylim(0, 7000)
    ax.set_xlabel("Tuned RF (MHz)"); ax.set_ylabel("Frequency (MHz)")
    ax.set_title("Frequency plan: IF 2441 MHz, LO 85-4200 MHz", fontsize=10.5, loc="left")
    ax.spines[["top", "right"]].set_visible(False); ax.grid(color="#ececec"); ax.set_axisbelow(True)
    ax.legend(fontsize=7, frameon=False, loc="upper left", bbox_to_anchor=(0.0, 0.93))
    fig.tight_layout(); fig.savefig(os.path.join(EXP, "auto_freqplan.png")); plt.close(fig)

    # ---------------------------------------------------------------- plot 2: worst in-band spur rejection vs RF
    fig, ax = plt.subplots(figsize=(9.5, 4.6), dpi=130)
    series = {"LB hi-side LO=IF+RF": (BLUE, "-"), "LB lo-side LO=IF-RF": (AQUA, "-"), "MB lo-side LO=IF-RF": (YELLOW, "-"),
              "HB single filter": (ORANGE, "-"), "HB split filters": (MAG, "-")}
    rfs = np.concatenate([np.arange(30, 1751, 5), np.arange(2950, 6001, 5)])
    data = {k: ([], []) for k in series}
    for rf in rfs:
        for lab, lo, band in plans(rf):
            w, _ = worst(rf, lo, band)
            data[lab][0].append(rf); data[lab][1].append(min(w, 80))
    for k, (col, ls) in series.items():
        x, y = data[k]
        if x:
            ax.plot(x, y, ls, color=col, lw=2 if ("split" in k or "hi-side" in k or k.startswith("MB")) else 1.4, label=k,
                    alpha=1 if ("split" in k or "hi-side" in k or k.startswith("MB")) else 0.75)
    ax.axhline(40, color="#999", lw=0.8, ls="--"); ax.text(80, 41.5, "40 dBc", fontsize=7.5, color="#666")
    ax.set_xlabel("Tuned RF (MHz)"); ax.set_ylabel("Worst in-passband spur rejection (dBc)")
    ax.set_title("Worst spur from an input inside the preselector passband (generic mixer spur table)", fontsize=10, loc="left")
    ax.set_ylim(-3, 85)
    ax.spines[["top", "right"]].set_visible(False); ax.grid(color="#ececec"); ax.set_axisbelow(True)
    ax.legend(fontsize=7.5, frameon=False, loc="lower center", ncol=2)
    fig.tight_layout(); fig.savefig(os.path.join(EXP, "auto_spurs.png")); plt.close(fig)

    # ---------------------------------------------------------------- plot 3: IF choice vs worst spur
    base = IF0
    fig, ax = plt.subplots(figsize=(9.5, 4.4), dpi=130)
    cmp = [(2440.0, BLUE, "IF 2440 (2.4 GHz ISM SAW)"), (2350.0, ORANGE, "IF 2350 (LTE B40 SAW, 2300-2400)")]
    summary = []
    for ifv, col, lab in cmp:
        IF0 = ifv
        xs, ys = [], []
        for rf in rfs:
            for l2, lo, band in plans(rf):
                if l2 in ("LB hi-side LO=IF+RF", "MB lo-side LO=IF-RF", "HB single filter"):
                    w, _ = worst(rf, lo, band); xs.append(rf); ys.append(min(w, 80))
        xs, ys = np.array(xs), np.array(ys)
        for seg in (xs < 1751, (xs > 1751) & (xs < 2200), xs > 2200):
            ax.plot(xs[seg], ys[seg], color=col, lw=2, label=lab if seg[0] else None)
        bad = xs[(ys < 30) & (xs > 2200)]
        summary.append(f"| {lab} | {bad.min():.0f}-{bad.max():.0f} MHz |" if len(bad) else f"| {lab} | none |")
    IF0 = base
    ax.axhline(40, color="#999", lw=0.8, ls="--")
    ax.set_xlabel("Tuned RF (MHz)"); ax.set_ylabel("Worst in-passband spur rejection (dBc)")
    ax.set_title("IF choice: LB hi-side LO, MB lo-side LO, HB single HPF 3.1-6.0 GHz", fontsize=10, loc="left")
    ax.axvspan(5150, 5895, color="#eef3fb", lw=0); ax.text(5170, 2, "5 GHz Wi-Fi / FPV", fontsize=7.5, color="#456")
    ax.set_ylim(-3, 85)
    ax.spines[["top", "right"]].set_visible(False); ax.grid(color="#ececec"); ax.set_axisbelow(True)
    ax.legend(fontsize=7.5, frameon=False, loc="lower left")
    fig.tight_layout(); fig.savefig(os.path.join(EXP, "auto_if_choice.png")); plt.close(fig)
    with open(os.path.join(EXP, "freqplan_tables.md"), "a") as f:
        f.write("\n## High-band RF span with a <30 dBc in-passband spur (HB single HPF 3.1-6 GHz)\n\n| IF | span |\n|---|---|\n" + "\n".join(summary) + "\n")
    print("\n".join(summary))

    # console summary of the worst offenders per band
    for k in series:
        x, y = data[k]
        if x:
            y = np.array(y); x = np.array(x)
            bad = x[y < 30]
            print(f"{k:22s} min rej {y.min():5.1f} dBc; RF with <30 dBc: "
                  + (f"{len(bad)} pts, {bad.min():.0f}-{bad.max():.0f} MHz" if len(bad) else "none"))
    for rf in [100, 1090, 3500, 4880, 5800]:
        for lab, lo, band in plans(rf):
            print(rf, lab, worst(rf, lo, band))

if __name__ == "__main__":
    main()
